def _design_evidence(c, hashes):
    """Find known generated bytes, including failed candidates in every state.

    A SHA is not a unique task identity. Retain every matching evidence record
    so a later success cannot hide a failed check or a different SKU binding.
    """
    hashes = {value for value in hashes if value}
    if not hashes:
        return {}
    clauses = []; values = []
    for digest in hashes:
        clauses.append('(result LIKE ? OR remote LIKE ?)');values.extend(['%'+digest+'%']*2)
    rows = c.execute("SELECT t.id,t.run_id,t.kind,t.status,t.payload,t.result,t.remote,r.workflow "
                     ",r.snapshot,r.status AS run_status FROM design_simple_tasks t JOIN design_simple_runs r ON r.id=t.run_id "
                     "WHERE t.kind IN ('master','image') AND ("+' OR '.join(clauses)+')', values)
    by_hash = {}
    for row in rows:
        def decoded(value):
            try:
                parsed=json.loads(value)
                return parsed if isinstance(parsed,dict) else {}
            except (ValueError,TypeError):
                return {}
        payload=decoded(row['payload']);result=decoded(row['result']);remote=decoded(row['remote'])
        candidates=[('result',result)]
        if isinstance(remote,dict):
            candidates.append(('saved_result',remote.get('saved_result')))
            if isinstance(remote.get('quality_candidates'),list):
                candidates.extend(('quality_candidate',candidate) for candidate in remote['quality_candidates'])
        for slot,candidate in candidates:
            if not isinstance(candidate,dict) or candidate.get('sha256') not in hashes:
                continue
            record={'task_id':row['id'],'run_id':row['run_id'],'kind':row['kind'],
                    'status':row['status'],'slot':slot,'workflow':row['workflow'],
                    'first_image':decoded(row['snapshot']).get('first_image'),
                    'run_status':row['run_status'],
                    'page':payload.get('page') if isinstance(payload.get('page'),dict) else {},
                    'product':payload.get('product') if isinstance(payload.get('product'),dict) else {},
                    'result':candidate}
            by_hash.setdefault(candidate['sha256'],[]).append(record)
    return by_hash


def _sku(draft, sku_id):
    return next((v for v in draft.get('skus', []) if v.get('sku_id') == sku_id), None)


def reference_board_ids(c, refs):
    """Identify all internal masters, including legacy bytes re-uploaded as photos.

    Read-only: omitting a reference from a publication does not alter the saved
    board, draft, asset, or any historical material version.
    """
    assets = {ref['asset_id']: s.get(c, 'media', ref['asset_id'], required=False)
              for ref in refs if ref.get('asset_id')}
    evidence = _design_evidence(c, [digest for asset in assets.values() if asset
                                   for digest in (asset.get('original_sha256'), asset.get('sha256'))])
    blocked = {ref['asset_id'] for ref in refs if ref.get('asset_id') and
               (design_quality.is_reference_board(ref) or ref.get('source') == 'design_master')}
    for ident, asset in assets.items():
        if not asset:
            continue
        records = evidence.get(asset.get('original_sha256'), []) + evidence.get(asset.get('sha256'), [])
        if design_quality.is_reference_board(asset) or any(
                record['kind'] == 'master' or design_quality.is_reference_board(record['result']) for record in records):
            blocked.add(ident)
    return blocked


def _verified_design_main(records, draft, sku=None):
    """Only the explicit story-workflow main slot may enter main-image review."""
    source = (draft or {}).get('source') or {}
    sku_ids = {v.get('sku_id') for v in (draft or {}).get('skus', [])}
    if sku is not None:
        sku_ids = {sku.get('sku_id')}
    bound_ids = {record['product'].get('sku_id') for record in records}
    if len(bound_ids) != 1 or not bound_ids.issubset(sku_ids) or None in bound_ids:
        return False
    current = [record for record in records if record['run_id'] == source.get('design_run_id')]
    if not current or not any(record['slot'] == 'result' for record in current):
        return False
    for record in records:
        result = record['result']; product = record['product']
        if (record.get('run_status')=='archived' or record['kind'] != 'image' or record['status'] != 'completed' or
                record['workflow'] not in {'archive-story-v5','archive-story-v6','archive-story-v7'} or
                result.get('asset_role') != design_quality.LISTING_MAIN_ROLE or
                (result.get('pipeline') or {}).get('workflow') != record['workflow'] or
                record['page'].get('type') != '主图' or
                not source.get('archive_digest') or result.get('archive_digest') != source['archive_digest'] or
                not design_quality.usable(result) or not product.get('source_hashes') or
                design_quality.source_hashes(result) != product['source_hashes']):
            return False
        if record['workflow']=='archive-story-v7':
            from app import design_contract
            presentation=source.get('design_presentation') or {}
            if (not design_contract.active({'pipeline':presentation}) or
                    presentation.get('first_image')!=record.get('first_image')):
                return False
    return True


def _archive_context(draft, sku):
    """Use frozen SKU facts, never mutable archive rows or stale supplier text."""
    from app.simple_design_prompts import clean_model_brief
    from . import product_archive
    source = draft.get('source') or {}
    frozen = next((v for v in source.get('skus', []) if
                   str(v.get('id', v.get('sku_id'))) == str(sku['sku_id'])), {})
    shared = {'facts': str(source.get('facts') or '')}
    overrides = set()
    for field, aliases in product_archive.FIELD_ALIASES.items():
        if product_archive.field_value(frozen, field)[1] != 'missing':
            overrides.update(alias.casefold() for alias in aliases)
            overrides.add(field.casefold())
    overrides.update(field.casefold() for field in (frozen.get('structured_facts') or {}))
    lines = [line for line in product_archive.facts_text(shared).splitlines()
             if re.split(r'[:：]', line, maxsplit=1)[0].strip().casefold() not in overrides]
    facts = clean_model_brief('\n'.join(dict.fromkeys(lines + product_archive.facts_text(frozen).splitlines())))
    quantity, state = product_archive.field_value(frozen, 'package_quantity')
    if state == 'missing':
        quantity, state = product_archive.field_value(shared, 'package_quantity')
    match = re.fullmatch(r'\s*(\d+)\s*(?:件|只|个|套|pcs?|pieces?)?\s*', str(quantity or ''), re.I)
    count = int(match[1]) if match and int(match[1]) > 0 else None
    return {'facts': facts, 'package_quantity': quantity, 'quantity_status': state,
            'sales_count': count, 'quantity_check_required': count is not None and count > 1}




def _stable_fingerprint(draft):
    source = draft.get('source') or {}
    value = {
        'brand': str(draft.get('brand') or '').strip().casefold(),
        'main_policy': main_image_policy.resolve(draft),
        'source': {key: source.get(key) for key in ('product_revision', 'design_run_id', 'facts', 'archive_digest', 'selected_sku_ids')},
        'images': draft.get('images') or [],
        'skus': [{key: sku.get(key) for key in ('sku_id', 'seller_sku', 'variant_key',
                                                'name', 'color', 'size')}
                 for sku in draft.get('skus', [])],
    }
    return hashlib.sha256(s.dump(value).encode()).hexdigest()


def attach_main(draft, sku_id, asset_id):
    """Return a new draft with exactly one main image for this SKU."""
    result = copy.deepcopy(draft)
    sku = _sku(result, sku_id)
    if not sku:
        raise HTTPException(404, '该 SKU 不在上架资料中')
    _set_main(sku, asset_id)
    return result


def _set_main(sku, asset_id):
    other = [ref for ref in sku.get('images', []) if ref.get('role') != 'main' and ref.get('asset_id') != asset_id]
    sku['images'] = [{'asset_id': asset_id, 'role': 'main'}, *other[:8]]


def bind_material_covers(c, draft, previous):
    """Use each SKU's designated current cover, retaining a valid merchant selection."""
    current_run = draft['source'].get('design_run_id')
    if not current_run or not draft['source'].get('design_presentation'):
        return
    prior_skus = {row['sku_id']: row for row in previous.get('skus', [])}
    for sku in draft['skus']:
        key = sku['variant_key']
        candidates = [ref['asset_id'] for ref in draft['images']
                      if ref.get('variant_key') == key and ref.get('design_run_id') == current_run
                      and ref.get('display_role') == 'sales_cover' and ref.get('source') == 'design_main_candidate']
        prior = prior_skus.get(sku['sku_id'], {})
        chosen = [ref['asset_id'] for ref in prior.get('images', []) if ref.get('role') == 'main']
        old_covers = {ref['asset_id'] for ref in previous.get('images', [])
                      if ref.get('variant_key') == key and ref.get('source') == 'design_main_candidate'}
        if chosen and not set(chosen) <= old_covers:
            candidates = chosen
        if len(candidates) != 1:
            continue
        try:
            validate_selection(c, draft, sku, candidates[0])
        except HTTPException as exc:
            if exc.status_code not in (404, 422):
                raise
            continue  # Keep the missing-main issue visible for an ineligible image.
        _set_main(sku, candidates[0])


def _assessment_key(asset, draft, sku):
    basis = json.dumps({'version': 5, 'layout_version': main_image_layout.VERSION,
                        'main_policy': main_image_policy.resolve(draft),
                        'sha256': asset['sha256'], 'sku_id': sku['sku_id'],
                        'brand': str(draft.get('brand') or '').strip().casefold(),
                        'color': sku.get('color', ''), 'facts': draft.get('source', {}).get('facts', ''),
                        'source_revision': draft.get('source', {}).get('product_revision'),
                        'archive_digest': draft.get('source', {}).get('archive_digest'),
                        'archive_context': _archive_context(draft, sku)},
                       ensure_ascii=False, sort_keys=True)
    return hashlib.sha256(basis.encode()).hexdigest()


def _screen_file(path, policy=None):
    """Cheap, reproducible hard checks; semantic claims require vision analysis."""
    try:
        with Image.open(path) as opened:
            oriented = ImageOps.exif_transpose(opened).convert('RGBA')
            im = Image.alpha_composite(Image.new('RGBA', oriented.size, 'white'), oriented).convert('RGB')
            width, height = im.size
            if max(width, height) < 1000 or min(width, height) < 500:
                return {'eligible': False, 'reason': '图片分辨率不足，长边至少 1000 像素、短边至少 500 像素',
                        'width': width, 'height': height}
            if policy and not policy['white_background_required']:
                return {'eligible': True, 'reason': '已记录首图策略的尺寸初筛通过，商品焦点、销售组成及当前类目要求仍须核对',
                        'width': width, 'height': height, 'semantic_checks_required': True}
            im.thumbnail((320, 320))
            w, h = im.size
            px = im.load()
            bright = lambda x, y: min(px[x, y]) >= 245 and max(px[x, y]) - min(px[x, y]) <= 9
            # Ignore a thin anti-aliased rim; corners and perimeter must still
            # look white.  This only rejects obviously non-white scenes.
            corners = []
            span = max(4, min(w, h) // 12)
            for yy in list(range(span)) + list(range(h - span, h)):
                for xx in list(range(span)) + list(range(w - span, w)):
                    corners.append(bright(xx, yy))
            border = [bright(x, 0) for x in range(w)] + [bright(x, h - 1) for x in range(w)]
            border += [bright(0, y) for y in range(h)] + [bright(w - 1, y) for y in range(h)]
            corner_ratio = sum(corners) / len(corners)
            border_ratio = sum(border) / len(border)
            if corner_ratio < .90 or border_ratio < .88:
                return {'eligible': False, 'reason': '背景不是接近纯白的单品图，场景图请作附图',
                        'width': width, 'height': height, 'white_corners': round(corner_ratio, 3)}
            foreground = sum(not bright(x, y) for y in range(h) for x in range(w)) / (w * h)
            if foreground < .012:
                return {'eligible': False, 'reason': '未识别到足够清晰的商品主体',
                        'width': width, 'height': height}
            return {'eligible': True, 'reason': '尺寸和外圈白底初筛通过；不能据白边认定内部背景合格，仍须核对实物、完整销售单位及杂物',
                    'width': width, 'height': height, 'white_corners': round(corner_ratio, 3),
                    'semantic_checks_required': True}
    except (OSError, UnidentifiedImageError, ValueError, Image.DecompressionBombError):
        return {'eligible': False, 'reason': '图片文件无法解码'}


def _candidate_refs(c, draft, sku, listing_id=None):
    refs = []
    for item in sku.get('images', []):
        if item.get('asset_id'):
            refs.append((item['asset_id'], 'sku'))
    for item in draft.get('images', []):
        if item.get('variant_key') == sku.get('variant_key') and item.get('asset_id'):
            refs.append((item['asset_id'], item.get('source') or item.get('role') or 'design'))
    registered = s.all_rows(c, 'main_image_candidate')
    generated_ids = {row['asset_id'] for row in registered
                     if row.get('sku_id') == sku['sku_id'] and row.get('origin') != 'merchant_upload'}
    for asset in s.all_rows(c, 'media'):
        if asset.get('sku_id') == sku['sku_id'] and asset['id'] not in generated_ids:
            refs.append((asset['id'], 'merchant_upload'))
    for row in registered:
        if row.get('sku_id') == sku['sku_id'] and row.get('listing_id') == listing_id and row.get('asset_id'):
            refs.append((row['asset_id'], row.get('origin') or 'generated'))
    seen = set()
    for asset_id, source in refs:
        if asset_id in seen:
            continue
        seen.add(asset_id)
        asset = s.get(c, 'media', asset_id, required=False)
        if asset:
            if asset_id in generated_ids:
                source = 'generated_from_source'
            elif asset.get('sku_id') == sku['sku_id']:
                source = 'merchant_upload'
            yield asset, source


def _candidate_screen(c, asset, draft=None, sku=None):
    """Recheck every candidate, including cached/attached generated images."""
    refs = list((draft or {}).get('images', []))
    refs.extend(ref for sku in (draft or {}).get('skus', []) for ref in sku.get('images', []))
    refs = [ref for ref in refs if ref.get('asset_id') == asset['id']]
    refs.append(asset | {'asset_id': asset['id']})
    if asset['id'] in reference_board_ids(c, refs):
        return {'eligible': False, 'reason': '产品母稿仅供内部设计参考，不能直接用于商品主图、附图或详情展示'}
    policy = main_image_policy.resolve(draft or {'product_type': 'GENERAL'})
    screen = _screen_file(media.path(asset['key']), policy)
    if not screen['eligible']:
        return screen
    evidence = _design_evidence(c, [asset.get('original_sha256'), asset.get('sha256')])
    records = evidence.get(asset.get('original_sha256'), []) + evidence.get(asset.get('sha256'), [])
    if records and _verified_design_main(records, draft, sku):
        if all(design_quality.generated(record['result']) for record in records):
            if hashlib.sha256(media.path(asset['key']).read_bytes()).hexdigest()!=asset['sha256']:
                return screen | {'eligible':False,'reason':'主图文件与保存记录不一致'}
            return screen | {'generation_protocol':design_quality.GENERATED_PROTOCOL,
                             'main_policy':policy,'semantic_checks_required':False,
                             'reason':'已完成指定主图生成，SKU、档案版本与文件记录一致'}
        return screen | {'frame_fill': {'status': 'requires_visual', 'method': 'generated_main_requires_visual'},
                         'main_policy': policy, 'category_status': policy['category_status'],
                         'generation_mode': 'reference_guided', 'semantic_checks_required': True,
                         'reason': '历史设计的指定首图保留原始生成记录；仍须按当前要求选择实物、销售组成、背景与构图'}
    if records:
        return screen | {'eligible': False, 'reason': '该图片是设计生成的成品；主图需从本款来源照片准备，不能把AI场景或母稿直接当作实物照片'}
    preserved = next((row for row in s.all_rows(c, 'main_image_preservation')
                      if row.get('sha256') == asset.get('original_sha256')), None)
    generated = preserved or any(row.get('asset_id') == asset['id'] and
        row.get('origin') != 'merchant_upload' for row in s.all_rows(c, 'main_image_candidate'))
    if generated:
        proof = (preserved or {}).get('proof') or {}
        if (not main_image_layout.preservation_valid(proof) or
                (proof.get('source_background') or {}).get('can_prepare') is not True or
                (proof.get('main_policy') or {}).get('profile') != policy['profile'] or
                proof.get('canvas_size') != [asset.get('width'), asset.get('height')]):
            return screen | {'eligible': False, 'reason': '历史主图缺少当前布局证明，请重新准备主图；历史图片保留'}
        fill = proof.get('frame_fill') or {}
    else:
        original = s.main().DATA_ROOT / 'commerce_originals' / str(asset.get('original_sha256') or '')
        if original.is_file():
            source_check = main_image_layout.inspect_source(original, policy)
            if not source_check['can_prepare']:
                return screen | {'eligible': False, 'reason': source_check['reason'], 'source_background': source_check}
            with Image.open(original) as raw:
                photo = ImageOps.exif_transpose(raw).convert('RGBA')
            fill = main_image_layout.frame_fill(photo, photo.size, policy['minimum_fill'])
        else:
            fill = {'status': 'requires_visual', 'method': 'opaque_photo_requires_visual'}
    if fill.get('status') not in {'eligible', 'reject', 'requires_visual'}:
        return screen | {'eligible': False, 'reason': '主图缺少完整的实物占比检查证据，请重新准备主图'}
    if fill.get('status') == 'reject':
        return screen | {'eligible': False, 'frame_fill': fill,
                         'reason': f"主图实物占比不足{policy['minimum_fill']:.0%}候选基线或透明度无法确认，请补充主体清晰、完整且更少留白的原图；类目规则优先"}
    source_bound = (not generated and sku is not None and asset.get('sku_id') == sku.get('sku_id')
                    and hashlib.sha256(media.path(asset['key']).read_bytes()).hexdigest() == asset.get('sha256'))
    return screen | {'frame_fill': fill, 'main_policy': policy, 'source_bound': source_bound,
                     'category_status': policy['category_status']}


def _assessment_eligible(assessment, asset=None, policy=None):
    return (assessment.get('decision') == 'eligible' and
            assessment.get('protocol') == ASSESSMENT_PROTOCOL and
            all((assessment.get('checks') or {}).get(key) is True for key in MAIN_CHECKS) and
            assessment.get('category_review_blocks_automatic_selection') is not True and
            not (policy or {}).get('category_review_blocks_automatic_selection',False) and
            bool(assessment.get('image_sha256')) and isinstance(assessment.get('source_sha256'),list) and
            bool(assessment['source_sha256']) and
            (asset is None or assessment.get('image_sha256') == asset.get('sha256')))


def candidate_report(listing_id):
    with s.main().db() as c:
        listing = s.get(c, 'listing', listing_id)
        draft = listing.get('draft') or {}
        report = []
        for sku in draft.get('skus', []):
            candidates = []
            for asset, source in _candidate_refs(c, draft, sku, listing_id):
                try:
                    screen = _candidate_screen(c, asset, draft, sku)
                except HTTPException:
                    screen = {'eligible': False, 'reason': '原图片文件不存在'}
                assessed = s.by_key(c, 'main_image_analysis', _assessment_key(asset, draft, sku))
                candidates.append({'asset_id': asset['id'], 'url': asset['url'], 'source': source,
                                   'screen': screen, 'assessment': assessed.get('assessment') if assessed else None,
                                   'chosen': any(x.get('role') == 'main' and x.get('asset_id') == asset['id']
                                                 for x in sku.get('images', []))})
            report.append({'sku_id': sku['sku_id'], 'seller_sku': sku['seller_sku'],
                           'color': sku.get('color', ''), 'candidates': candidates})
        return {'listing_id': listing_id, 'revision': listing['revision'], 'skus': report}


def validate_selection(c, draft, sku, asset_id):
    """Read-only validation for draft edits and production submission."""
    asset = s.get(c, 'media', asset_id)
    if asset.get('sku_id') not in (None, sku['sku_id']):
        raise HTTPException(422, sku['seller_sku'] + '：主图属于其他 SKU')
    try:
        screen = _candidate_screen(c, asset, draft, sku)
    except HTTPException:
        raise HTTPException(422, sku['seller_sku'] + '：主图文件不存在') from None
    if not screen['eligible']:
        raise HTTPException(422, sku['seller_sku'] + '：' + screen['reason'])
    if screen.get('generation_protocol')==design_quality.GENERATED_PROTOCOL or screen.get('source_bound'):
        if main_image_policy.resolve(draft)['category_review_blocks_automatic_selection']:
            raise HTTPException(422,'当前类目的主图要求尚未明确，请先补齐平台类目信息')
        return True
    analysis = s.by_key(c, 'main_image_analysis', _assessment_key(asset, draft, sku))
    if not analysis or not _assessment_eligible(analysis.get('assessment', {}), asset, main_image_policy.resolve(draft)):
        reason = (analysis or {}).get('assessment', {}).get('reason') or '请在设计工作台完成主图，或上传明确绑定本 SKU 的商品图片'
        raise HTTPException(422, sku['seller_sku'] + '：主图尚未通过检查：' + reason)
    return True


def validate_auxiliary(c, draft, sku):
    """Identify historical design photos whose frozen variant colour drifted.

    The caller may omit excluded assets from the outgoing Amazon payload while
    leaving the user's original draft and material versions untouched.
    """
    from . import gallery_assembly
    run_id = (draft.get('source') or {}).get('design_run_id')
    excluded = []
    reason_by_asset = {}
    refs = list(draft.get('images', [])) + [v for v in sku.get('images', []) if v.get('role') != 'main']
    reference_boards = reference_board_ids(c, refs)
    assets={v['asset_id']:s.get(c,'media',v['asset_id'],required=False) for v in refs if v.get('asset_id')}
    evidence=_design_evidence(c,[value for asset in assets.values() if asset
                                for value in (asset.get('original_sha256'),asset.get('sha256'))])
    for ref in refs:
        if ref.get('variant_key') not in (None, sku.get('variant_key')):
            continue
        asset_id = ref.get('asset_id')
        if not asset_id:
            continue
        asset = assets.get(asset_id)
        if asset_id in reference_boards:
            reason = '产品母稿仅供内部设计参考，不能直接用于商品主图、附图或详情展示'
        elif not asset:
            reason = '图片记录不存在'
        else:
            records=evidence.get(asset.get('original_sha256'),[])+evidence.get(asset.get('sha256'),[])
            own=[record for record in records if record['product'].get('sku_id')==sku.get('sku_id')]
            current=[record for record in own if (record['run_id']==run_id or
                     gallery_assembly.matches_section_record(draft,sku,record)) and
                     record['status']=='completed' and record['slot']=='result']
            if asset.get('sku_id') not in (None,sku.get('sku_id')):
                reason = '设计图属于其他商品 SKU'
            elif records:
                if any(record.get('run_status')=='archived' for record in records):
                    reason = '该设计已归档，只供历史回溯，不能用于当前图库或上架'
                elif asset.get('sku_id') is None and len({record['product'].get('sku_id') for record in records})>1:
                    reason = '同一设计图片存在多个 SKU 归属且资产未明确绑定本款，请核验'
                elif not current:
                    reason = ('设计任务的颜色或变体标识与当前 SKU 不一致；历史候选不能当作商家原图绕过检查'
                              if any(record['product'].get('sku_id') is None and
                                     str(record['product'].get('color') or '').strip()!=str(sku.get('color') or '').strip()
                                     for record in records) else
                              '设计候选没有绑定当前已完成任务及本 SKU；失败、历史或其他款图片不能当作商家原图绕过检查')
                elif any(record['result'].get('archive_digest')!=(draft.get('source') or {}).get('archive_digest') for record in current):
                    reason = '设计图对应的商品档案事实版本与当前刊登资料不同'
                elif any(not design_quality.usable(record['result']) or
                         not record['product'].get('source_hashes') or
                         design_quality.source_hashes(record['result'])!=record['product']['source_hashes']
                         for record in own):
                    reason = '设计图尚未取得真实原图保真确认：同一图片的审核有失败、不确定、旧协议或证据冲突，请核验；后续成功不能掩盖先前问题'
                else:
                    continue
            elif asset.get('sku_id') == sku.get('sku_id'):
                continue
            else:
                reason = '无法确认设计图对应当前 SKU'
        excluded.append(asset_id)
        reason_by_asset[asset_id] = reason
    return {'excluded_asset_ids': sorted(set(excluded)), 'reasons': reason_by_asset}


def choose(listing_id, payload):
    from . import catalog
    revision = s.quantity(payload.get('revision'), 1)
    sku_id = s.quantity(payload.get('sku_id'), 1)
    asset_id = s.quantity(payload.get('asset_id'), 1)
    with s.main().db() as c:
        listing = s.get(c, 'listing', listing_id)
        if listing['revision'] != revision:
            raise HTTPException(409, '商品资料已变化，请刷新后选择')
        draft = listing.get('draft') or {}
        sku = _sku(draft, sku_id)
        if not sku:
            raise HTTPException(404, '该 SKU 不在上架资料中')
        valid_ids = {asset['id'] for asset, _ in _candidate_refs(c, draft, sku, listing_id)}
        if asset_id not in valid_ids:
            raise HTTPException(422, '只能选择当前 SKU 已有的成品图或商品照片；母稿仅供内部参考')
        validate_selection(c, draft, sku, asset_id)
    return catalog.update_draft(listing_id, {'revision': revision,
                                              'draft': attach_main(draft, sku_id, asset_id)})


def _require_archive_snapshot(draft):
    source=draft.get('source') or {}
    digest=source.get('archive_digest') if isinstance(source,dict) else None
    if not isinstance(digest,str) or not re.fullmatch('[0-9a-f]{64}',digest):
        raise HTTPException(409,'历史上架资料缺少商品档案事实快照，请先从商品档案重新准备资料；历史图片仍保留')
    return source


def enqueue(listing_id, sku_id=None, candidate_asset_id=None, retry_key=''):
    with s.transaction() as c:
        listing = s.get(c, 'listing', listing_id)
        draft = listing.get('draft') or {}
        if not draft.get('skus'):
            raise HTTPException(422, '请先生成商品资料')
        _require_archive_snapshot(draft)
        if sku_id is not None and not _sku(draft, sku_id):
            raise HTTPException(404, '该 SKU 不在上架资料中')
        if candidate_asset_id is not None:
            if sku_id is None:
                raise HTTPException(422, '上传主图必须指定 SKU')
            asset = s.get(c, 'media', candidate_asset_id)
            if asset.get('sku_id') != sku_id:
                raise HTTPException(422, '上传图片未绑定当前 SKU')
            s.put(c, 'main_image_candidate', f"{listing_id}:{sku_id}:{candidate_asset_id}",
                  {'listing_id': listing_id, 'sku_id': sku_id,
                   'asset_id': candidate_asset_id, 'origin': 'merchant_upload'})
        ids = [sku_id] if sku_id is not None else [v['sku_id'] for v in draft['skus']]
        fingerprint = _stable_fingerprint(draft)
        jobs = [s.enqueue(c, 'main_image',
                          f"main-image:{listing_id}:{listing['revision']}:{sid}:{candidate_asset_id or 0}"
                          + ':layout:' + main_image_layout.VERSION
                          + (':' + retry_key if retry_key else ''),
                          {'listing_id': listing_id, 'revision': listing['revision'], 'sku_id': sid,
                           'draft_fingerprint': fingerprint, 'candidate_asset_id': candidate_asset_id,
                           'main_layout_version': main_image_layout.VERSION,
                           'main_policy_version': main_image_policy.VERSION})
                for sid in ids]
        return jobs[0] if sku_id is not None else {'jobs': jobs}














def run_job(job):
    """Worker entry point. Never posts an image or a listing to Amazon."""
    ident = job['payload']['listing_id']
    with s.main().db() as c:
        listing = s.get(c, 'listing', ident)
        source=_require_archive_snapshot(listing.get('draft') or {})
        if (job['payload'].get('main_layout_version') not in (None, main_image_layout.VERSION) or
                job['payload'].get('main_policy_version') not in (None, main_image_policy.VERSION)):
            raise HTTPException(409, '主图检查规则已更新，请重新创建准备任务；历史图片保留')
        selected = [v for v in listing.get('draft', {}).get('skus', [])
                    if job['payload'].get('sku_id') == v['sku_id']]
        if (listing['revision'] != job['payload']['revision'] and
                _stable_fingerprint(listing.get('draft') or {}) != job['payload'].get('draft_fingerprint')):
            if selected:
                main = next((v for v in selected[0].get('images', []) if v.get('role') == 'main'), None)
                if main:
                    try:
                        validate_selection(c, listing['draft'], selected[0], main['asset_id'])
                        return {'listing_id': ident, 'skus': [{'sku_id': selected[0]['sku_id'],
                                 'status': 'attached', 'asset_id': main['asset_id'], 'already_attached': True}]}
                    except HTTPException:
                        pass
            raise HTTPException(409, '商品资料已变化，请重新运行主图准备')
    with s.main().db() as c:
        from . import product_archive
        product=s.get(c,'product',listing['product_id'])
        if product_archive.fact_digest(c,product,source.get('selected_sku_ids'))!=source['archive_digest']:
            raise HTTPException(409,'商品档案实物事实已变化，请更新上架资料后再准备主图')
    if not selected:
        raise HTTPException(422, '没有可处理的 SKU')
    return _attach_generated_mains(job,listing,selected)


def _attach_generated_mains(job, listing, selected):
    """Select the designated current main, never add an AI review or redraw."""
    from . import catalog,product_archive
    outcomes=[]
    for sku in selected:
        chosen=None;reasons=[]
        with s.main().db() as c:
            current=s.get(c,'listing',listing['id']);draft=current['draft']
            if _stable_fingerprint(draft)!=job['payload'].get('draft_fingerprint'):
                raise HTTPException(409,'商品资料已变化，请重新准备主图')
            frozen=draft.get('source') or {};product=s.get(c,'product',current['product_id'])
            if product_archive.fact_digest(c,product,frozen.get('selected_sku_ids'))!=frozen.get('archive_digest'):
                raise HTTPException(409,'商品档案已变化，请更新资料')
            candidates=list(_candidate_refs(c,draft,sku,listing['id']))
            preferred=job['payload'].get('candidate_asset_id')
            if preferred:candidates.sort(key=lambda pair:pair[0]['id']!=preferred)
            for asset,_ in candidates:
                screen=_candidate_screen(c,asset,draft,sku)
                if screen.get('eligible') and (screen.get('generation_protocol')==design_quality.GENERATED_PROTOCOL or screen.get('source_bound')):
                    try:validate_selection(c,draft,sku,asset['id'])
                    except HTTPException as exc:
                        reasons.append(str(exc.detail));continue
                    chosen=asset;break
                reasons.append(screen.get('reason','图片未完成'))
        if chosen:
            listing=catalog.update_draft(listing['id'],{'revision':current['revision'],
                'draft':attach_main(draft,sku['sku_id'],chosen['id'])})
            # Only our selected main reference changed; preserve the concurrency fence for the next SKU.
            job={**job,'payload':{**job['payload'],'draft_fingerprint':_stable_fingerprint(listing['draft'])}}
            outcomes.append({'sku_id':sku['sku_id'],'status':'attached','asset_id':chosen['id']})
        else:
            outcomes.append({'sku_id':sku['sku_id'],'status':'missing',
                'reason':'；'.join(dict.fromkeys(reasons))[:500] or '请在设计工作台完成本款主图'})
    return {'listing_id':listing['id'],'skus':outcomes}
